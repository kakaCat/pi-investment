/**
 * 补全股票名称
 * @param symbol - 股票代码（6位数字）
 * @returns 股票名称，如果映射表中没有则返回代码本身
 */
export function getStockName(symbol: string): string {
  // 去掉可能的市场前缀（sh/sz）
  const code = symbol.replace(/^(sh|sz)/i, '');
  return STOCK_NAME_MAP[code] || symbol;
}
